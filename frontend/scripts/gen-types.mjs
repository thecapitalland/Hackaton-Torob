import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compileFromFile } from "json-schema-to-typescript";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const schemaDir = path.join(root, "shared", "schemas");
const outDir = path.join(here, "../src/types");
await fs.mkdir(outDir, { recursive: true });

const decision = await compileFromFile(path.join(schemaDir, "decision.json"), {
  bannerComment: "/* Generated by npm run gen:types. Do not edit by hand. */",
  style: { singleQuote: false },
});
const response = await compileFromFile(path.join(schemaDir, "chat-response.json"), {
  bannerComment: "/* Generated by npm run gen:types. Do not edit by hand. */",
  style: { singleQuote: false },
});
await fs.writeFile(path.join(outDir, "decision.gen.ts"), decision, "utf8");
await fs.writeFile(path.join(outDir, "chat-response.gen.ts"), response, "utf8");
await fs.writeFile(
  path.join(outDir, "api.gen.ts"),
  '/* Generated by npm run gen:types. Do not edit by hand. */\nexport * from "./decision.gen";\nexport type { ChatResponse } from "./chat-response.gen";\n',
  "utf8",
);
console.log("Generated frontend/src/types/api.gen.ts from shared/schemas.");
